#!/usr/bin/env bash
# Refreshes `vendor/` from an upstream gleam-lang/gleam checkout.
#
#   ./vendor.sh /path/to/gleam-checkout [git-ref]
#
# The bridge links against `gleam-core` (parser + untyped AST) and
# `gleam-format` (printer) only, so the other workspace members are not copied.
# Test fixtures and snapshot files are dropped afterwards: they are the bulk of
# the tree and the bridge never reads them.
#
# ## What this script also regenerates
#
# Two files in `vendor/` are *not* verbatim copies, because the upstream crates
# cannot compile outside their own workspace:
#
#   * `vendor/Cargo.toml` — the workspace root the vendored crates inherit
#     their dependency versions from. Written from the upstream
#     `[workspace.dependencies]` table, filtered to the keys the vendored
#     crates actually use.
#   * `vendor/hexpm/` — a trimmed Hex client. `gleam-core` needs only the
#     version algebra and the `ApiError` variant list; the HTTP client,
#     protobuf payloads and RSA verification are dropped so the bridge builds
#     without `ring`, `prost` or a `build.rs`.
#
# Both are regenerated here rather than hand-maintained, so a version bump is a
# one-command operation.
set -euo pipefail

SOURCE=${1:?usage: vendor.sh <gleam-checkout> [git-ref]}
REF=${2:-}
HERE=$(cd "$(dirname "$0")" && pwd)

if [ -n "$REF" ]; then
  git -C "$SOURCE" checkout --quiet "$REF"
fi

VERSION=$(sed -n 's/^version = "\(.*\)"/\1/p' "$SOURCE/compiler-core/Cargo.toml" | head -1)

# `hexpm` is a trimmed copy rather than a wholesale copy, and two of its files
# (`Cargo.toml`, `src/lib.rs`) are hand-maintained. Preserve them across the
# refresh so a version bump does not silently delete the shim.
HEXPM_KEEP=$(mktemp -d)
if [ -d "$HERE/vendor/hexpm" ]; then
  cp -R "$HERE/vendor/hexpm" "$HEXPM_KEEP/hexpm"
fi

rm -rf "${HERE:?}/vendor"
mkdir -p "$HERE/vendor"

for crate in compiler-core format pretty-arena src-span erlang-generation erlang-term-format; do
  cp -R "$SOURCE/$crate" "$HERE/vendor/$crate"
done

cp "$SOURCE/LICENCE" "$HERE/vendor/LICENCE"

# Drop the paths listed in .vendor-excludes, ignoring the comments.
while IFS= read -r path; do
  case "$path" in ''|'#'*) continue ;; esac
  rm -rf "${HERE:?}/vendor/$path"
done < "$HERE/.vendor-excludes"

# ── Workspace root ───────────────────────────────────────────────────
#
# The vendored crates inherit dependency versions from upstream's workspace
# root (`xxhash-rust.workspace = true`, …). Without one Cargo refuses to load
# them at all:
#
#   error inheriting `async-trait` from workspace root manifest's
#   `workspace.dependencies.async-trait`: failed to find a workspace root
#
# The members list is fixed; the dependency table is copied out of the
# upstream manifest and filtered to the keys the vendored crates reference.
{
  cat <<'HEADER'
# SPDX-License-Identifier: Apache-2.0
# SPDX-FileCopyrightText: 2020 The Gleam contributors
#
# Workspace root for the *vendored* Gleam crates. Generated by `vendor.sh`;
# do not edit by hand. See that script for why it exists.

[workspace]
resolver = "2"
members = [
  "compiler-core",
  "erlang-generation",
  "erlang-term-format",
  "format",
  "hexpm",
  "pretty-arena",
  "src-span",
]

[workspace.dependencies]
HEADER

  # Every `key.workspace = true` or `key = { workspace = true }` the vendored
  # crates reference, in upstream's own order and spelling.
  keys=$(grep -hoE '^[a-zA-Z0-9_-]+(\.workspace = true| = \{ workspace = true)' \
           "$HERE"/vendor/*/Cargo.toml | sed -E 's/^([a-zA-Z0-9_-]+).*/\1/' | sort -u)

  awk -v keys="$keys" '
    BEGIN { n = split(keys, wanted, "\n"); for (i = 1; i <= n; i++) want[wanted[i]] = 1; inside = 0 }
    /^\[workspace\.dependencies\]/ { inside = 1; next }
    /^\[/ { inside = 0 }
    inside && /^[a-zA-Z0-9_-]+ *=/ {
      key = $0; sub(/ *=.*/, "", key)
      if (key in want) print $0
    }
  ' "$SOURCE/Cargo.toml"
} > "$HERE/vendor/Cargo.toml"

# ── Trimmed hexpm ────────────────────────────────────────────────────
#
# `gleam-core` names `hexpm::version::*`, a handful of data types and
# `hexpm::ApiError`. The version algebra is copied verbatim (minus its tests,
# which need a test module that is not copied); everything else is written by
# `vendor_hexpm` below.
mkdir -p "$HERE/vendor/hexpm/src/version"
cp "$SOURCE/hexpm/src/version.rs" "$HERE/vendor/hexpm/src/version.rs"

# Restore the hand-maintained shim files, then re-copy the upstream version
# algebra over them (the algebra is upstream's, the crate root is ours).
if [ -f "$HEXPM_KEEP/hexpm/Cargo.toml" ]; then
  cp "$HEXPM_KEEP/hexpm/Cargo.toml" "$HERE/vendor/hexpm/Cargo.toml"
fi
if [ -f "$HEXPM_KEEP/hexpm/src/lib.rs" ]; then
  cp "$HEXPM_KEEP/hexpm/src/lib.rs" "$HERE/vendor/hexpm/src/lib.rs"
fi
rm -rf "$HEXPM_KEEP"
cp "$SOURCE/hexpm/src/version/lexer.rs" "$HERE/vendor/hexpm/src/version/lexer.rs"
cp "$SOURCE/hexpm/src/version/parser.rs" "$HERE/vendor/hexpm/src/version/parser.rs"

# The copied `version.rs` declares `mod tests;`, whose file is not copied.
sed -i.bak '/^#\[cfg(test)\]$/{N;/mod tests;/d;}' "$HERE/vendor/hexpm/src/version.rs"
rm -f "$HERE/vendor/hexpm/src/version.rs.bak"

# `version/lexer.rs` carries an inline `#[cfg(test)] mod tests { … }` block that
# references helpers only the upstream test module provides.
python3 - "$HERE/vendor/hexpm/src/version/lexer.rs" <<'PY'
import sys
path = sys.argv[1]
source = open(path).read()
marker = "#[cfg(test)]\nmod tests {"
if marker in source:
    source = source[: source.index(marker)].rstrip() + "\n"
    open(path, "w").write(source)
PY

# `erlang-term-format` has the same inline-test problem.
python3 - "$HERE/vendor/erlang-term-format/src/lib.rs" <<'PY'
import sys
path = sys.argv[1]
source = open(path).read()
source = source.replace("#[cfg(test)]\nmod tests;\n\n", "")
source = source.replace("#[cfg(test)]\n#[macro_use]\nextern crate pretty_assertions;\n\n", "")
open(path, "w").write(source)
PY

echo "vendored gleam $VERSION from $SOURCE"
echo "NOTE: vendor/hexpm/src/lib.rs and vendor/hexpm/Cargo.toml are preserved"
echo "      verbatim across a refresh (see vendor/README.md). After a version"
echo "      bump, re-check them against upstream hexpm/src/lib.rs: a new"
echo "      ApiError variant or a changed data type is a compile error in"
echo "      gleam-core, which is the tripwire that keeps them honest."
